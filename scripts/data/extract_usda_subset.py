"""
Extract the USDA FoodData Central entries used by FOODLEK's seed ingredients.

Input: the per-country SQLite build published by the open-source project
CodeJetNet/food-data (https://github.com/CodeJetNet/food-data), which embeds
USDA FoodData Central (SR Legacy + Foundation, public domain) alongside Open
Food Facts data (ODbL). Only USDA rows are read here.

Usage:
    python3 scripts/data/extract_usda_subset.py path/to/foods-FR.db

Output: data/reference/usda-subset.json (committed, reviewed in diffs).

Why USDA and not Ciqual for the seed: Ciqual (ANSES, Licence Ouverte) is the
preferred reference for France and has a dedicated importer
(scripts/data/import-ciqual.ts). The seed must however be reproducible in
environments where the Ciqual files cannot be downloaded; USDA values are
public domain, versioned and identified by FDC id, so they are a legitimate,
traceable fallback. Every value keeps its source in the database.
"""
