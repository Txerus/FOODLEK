NUTRIENTS = {
    "energyKcal": "n1008",
    "proteinG": "n1003",
    "fatG": "n1004",
    "carbsG": "n1005",
    "fiberG": "n1079",
    "sugarsG": "n2000",
    "saturatedFatG": "n1258",
    "sodiumMg": "n1093",
}

SOURCE_LABELS = {
    "usda_sr": ("USDA_SR_LEGACY", "USDA FoodData Central – SR Legacy", "SR Legacy (2018-04)"),
    "usda_foundation": ("USDA_FOUNDATION", "USDA FoodData Central – Foundation Foods", "Foundation Foods"),
}


def main(db_path: str) -> None:
    db = sqlite3.connect(db_path)
    meta = dict(db.execute("select key, value from meta").fetchall())
    cols = ", ".join(NUTRIENTS.values())
    foods = {}
    for fdc in FDC_IDS:
        row = db.execute(
            f"select id, name, source, {cols} from foods where source_id = ? and source like 'usda%'",
            (fdc,),
        ).fetchone()
        if row is None:
            raise SystemExit(f"FDC id {fdc} not found in {db_path}")
        food_id, name, source = row[0], row[1], row[2]
        values = row[3:]
        kind, label, version = SOURCE_LABELS[source]
        portions = [
            {"description": d, "grams": g}
            for d, g in db.execute("select description, grams from portions where food_id = ?", (food_id,))
        ]
        foods[fdc] = {
            "fdcId": fdc,
            "name": name,
            "source": kind,
            "sourceLabel": label,
            "sourceVersion": version,
            "per100g": {
                key: (None if v is None else round(float(v), 4)) for key, v in zip(NUTRIENTS.keys(), values)
            },
            "portions": portions,
            "url": f"https://fdc.nal.usda.gov/food-details/{fdc}/nutrients",
        }
    out = {
        "_about": (
            "USDA FoodData Central values (public domain) for FOODLEK seed ingredients. "
            "Generated by scripts/data/extract_usda_subset.py; do not edit by hand."
        ),
        "extractedFrom": {
            "dataset": "CodeJetNet/food-data foods-FR.db",
            "builtAt": meta.get("builtAt"),
            "attribution": meta.get("attribution"),
        },
        "license": "USDA FoodData Central data are in the public domain (CC0 1.0).",
        "foods": foods,
    }
    target = Path(__file__).resolve().parents[2] / "data" / "reference" / "usda-subset.json"
    target.write_text(json.dumps(out, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {len(foods)} foods to {target}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(sys.argv[1])
